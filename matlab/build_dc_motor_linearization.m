function model = build_dc_motor_linearization
%BUILD_DC_MOTOR_LINEARIZATION Part I, Question 2(b): triple-integrator output.
project = setup_project; source = 'part1_dc_motor';
model = 'part1_dc_motor_linearization';
if bdIsLoaded(model), close_system(model,0); end
load_system(fullfile(project.simulink,[source '.slx']));
save_system(source,fullfile(project.simulink,[model '.slx']));
ports = get_param([model '/Voltage input u'],'PortHandles');
delete_line(get_param(ports.Outport(1),'Line'));
delete_block([model '/Voltage input u']);
controller = [model '/Linearizing controller'];
add_block('built-in/Subsystem',controller,'Position',[280 175 470 325]);
names = {'v','omega','ia'};
for index = 1:3
    add_block('simulink/Ports & Subsystems/In1',[controller '/' names{index}], ...
        'Port',num2str(index),'Position',[35 90*index 65 90*index+20]);
end
add_block('simulink/Signal Routing/Mux',[controller '/Measured states'], ...
    'Inputs','2','Position',[130 205 135 285]);
add_block('simulink/User-Defined Functions/Fcn',[controller '/Acceleration from states'], ...
    'Expr','(KT*u(2)-d1*u(1)-d2*u(1)*abs(u(1)))/J', ...
    'Position',[220 225 515 275]);
add_block('simulink/Signal Routing/Mux',[controller '/Control arguments'], ...
    'Inputs','4','Position',[590 80 595 220]);
add_block('simulink/User-Defined Functions/Fcn',[controller '/Linearizing voltage'], ...
    'Expr','J*La/KT*u(1)+Ke*u(2)+Ra*u(3)+La/KT*(d1+2*d2*abs(u(2)))*u(4)', ...
    'Position',[690 115 1100 175]);
add_block('simulink/Ports & Subsystems/Out1',[controller '/u'], ...
    'Port','1','Position',[1170 135 1200 155]);
wire(controller,{'omega/1','Measured states/1';'ia/1','Measured states/2'; ...
    'Measured states/1','Acceleration from states/1'; ...
    'v/1','Control arguments/1';'omega/1','Control arguments/2'; ...
    'ia/1','Control arguments/3';'Acceleration from states/1','Control arguments/4'; ...
    'Control arguments/1','Linearizing voltage/1';'Linearizing voltage/1','u/1'});
note = Simulink.Annotation(controller,sprintf([ ...
    'alpha = (KT*ia - d1*omega - d2*omega*abs(omega))/J\n' ...
    'u = J*La/KT*v + Ke*omega + Ra*ia + La/KT*(d1+2*d2*abs(omega))*alpha']));
note.Position = [35 15 1200 60];
add_block('simulink/Sources/Step',[model '/Virtual jerk v'], ...
    'Time','0.2','Before','0','After','1','Position',[65 180 115 220]);
wire(model,{'Virtual jerk v/1','Linearizing controller/1'; ...
    'Nonlinear DC motor/2','Linearizing controller/2'; ...
    'Nonlinear DC motor/3','Linearizing controller/3'; ...
    'Linearizing controller/1','Nonlinear DC motor/1'; ...
    'Linearizing controller/1','Voltage scope/1'});
set_param([model '/Jerk scope'],'NumInputPorts','2');
wire(model,{'Virtual jerk v/1','Jerk scope/2'});
ports = get_param(controller,'PortHandles');
set_param(get_param(ports.Outport(1),'Line'),'Name','u');
ports = get_param([model '/Virtual jerk v'],'PortHandles');
set_param(get_param(ports.Outport(1),'Line'),'Name','v');
notes = find_system(model,'FindAll','on','SearchDepth',1,'Type','annotation');
delete(notes);
note = Simulink.Annotation(model,sprintf([ ...
    'Part I - Question 2(b): input-output feedback linearization\n' ...
    'Virtual input v is angular jerk: theta third derivative = v.\n' ...
    'Zero initial states; v steps from 0 to 1 rad/s^3 at 0.2 s.\n' ...
    'No tracking/stabilizing controller yet; states are fed back without numerical derivatives.']));
note.Position = [60 20 1100 105];
save_system(model);
Simulink.exportToVersion(model,fullfile(project.simulink,[model '_R2021a.slx']),'R2021a');
end

function wire(system,connections)
for index = 1:size(connections,1)
    add_line(system,connections{index,1},connections{index,2},'autorouting','on');
end
end
