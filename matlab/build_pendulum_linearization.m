function model = build_pendulum_linearization
%BUILD_PENDULUM_LINEARIZATION Part I, Question 1(b): exact cancellation.
project = setup_project;
source = 'part1_pendulum';
load_system(fullfile(project.simulink, [source '.slx']));
model = 'part1_pendulum_linearization';
if bdIsLoaded(model), close_system(model, 0); end
new_system(model);
workspace = get_param(model, 'ModelWorkspace');
original = get_param(source, 'ModelWorkspace');
names = {'m', 'l', 'g', 'k', 'theta0', 'omega0'};
for index = 1:numel(names)
    assignin(workspace, names{index}, getVariable(original, names{index}));
end
set_param(model, 'SolverType', 'Variable-step', 'Solver', 'ode45', ...
    'RelTol', '1e-8', 'AbsTol', '1e-10', 'MaxStep', '0.005', ...
    'StopTime', '2', 'ReturnWorkspaceOutputs', 'on', ...
    'SaveOutput', 'off', 'SaveTime', 'off', 'SignalLogging', 'off', ...
    'Location', [40 80 1380 850]);
plant = [model '/Nonlinear pendulum'];
add_block('built-in/Subsystem', plant, 'Position', [590 180 770 300]);
blocks = {'Input projection', 'Inverse inertia', 'Angular acceleration', ...
    'Angular velocity', 'Angle', 'sin theta', 'Gravity', 'Friction', 'cos theta'};
for index = 1:numel(blocks)
    add_block([source '/' blocks{index}], [plant '/' blocks{index}]);
end
port(plant, 'In1', 'u', 1, [50 350 80 370]);
port(plant, 'Out1', 'theta', 1, [965 230 995 250]);
port(plant, 'Out1', 'omega', 2, [965 310 995 330]);
port(plant, 'Out1', 'alpha', 3, [965 390 995 410]);
wire(plant, {'u/1','Input projection/1'; 'cos theta/1','Input projection/2'; ...
    'Input projection/1','Inverse inertia/1'; ...
    'Inverse inertia/1','Angular acceleration/3'; ...
    'sin theta/1','Gravity/1'; 'Gravity/1','Angular acceleration/1'; ...
    'Angular velocity/1','Friction/1'; 'Friction/1','Angular acceleration/2'; ...
    'Angular acceleration/1','Angular velocity/1'; ...
    'Angular velocity/1','Angle/1'; 'Angle/1','sin theta/1'; ...
    'Angle/1','cos theta/1'; 'Angle/1','theta/1'; ...
    'Angular velocity/1','omega/1'; 'Angular acceleration/1','alpha/1'});

controller = [model '/Linearizing controller'];
add_block('built-in/Subsystem', controller, 'Position', [275 180 465 300]);
port(controller, 'In1', 'v', 1, [30 55 60 75]);
port(controller, 'In1', 'theta', 2, [30 155 60 175]);
port(controller, 'In1', 'omega', 3, [30 255 60 275]);
port(controller, 'Out1', 'u', 1, [650 145 680 165]);
add_block('simulink/Math Operations/Gain', [controller '/Inertia'], ...
    'Gain', 'm*l^2', 'Position', [160 45 230 85]);
add_block('simulink/Math Operations/Trigonometric Function', [controller '/sin theta'], ...
    'Operator', 'sin', 'Position', [115 135 155 165]);
add_block('simulink/Math Operations/Gain', [controller '/Gravity compensation'], ...
    'Gain', 'm*g*l', 'Position', [220 130 300 170]);
add_block('simulink/Math Operations/Gain', [controller '/Friction compensation'], ...
    'Gain', 'k', 'Position', [160 245 230 285]);
add_block('simulink/Math Operations/Sum', [controller '/Numerator'], ...
    'Inputs', '+-+', 'Position', [370 115 400 175]);
add_block('simulink/Math Operations/Trigonometric Function', [controller '/cos theta'], ...
    'Operator', 'cos', 'Position', [310 330 350 360]);
add_block('simulink/Math Operations/Product', [controller '/Divide by cos theta'], ...
    'Inputs', '*/', 'Position', [530 135 565 180]);
wire(controller, {'v/1','Inertia/1'; 'theta/1','sin theta/1'; ...
    'sin theta/1','Gravity compensation/1'; 'omega/1','Friction compensation/1'; ...
    'Inertia/1','Numerator/1'; 'Gravity compensation/1','Numerator/2'; ...
    'Friction compensation/1','Numerator/3'; 'theta/1','cos theta/1'; ...
    'Numerator/1','Divide by cos theta/1'; ...
    'cos theta/1','Divide by cos theta/2'; 'Divide by cos theta/1','u/1'});
note = Simulink.Annotation(controller, ...
    'u = (m*l^2*v - m*g*l*sin(theta) + k*omega)/cos(theta)');
note.Position = [40 10 700 30];
add_block('simulink/Sources/Step', [model '/Virtual acceleration v'], ...
    'Time', '0.2', 'Before', '0', 'After', '0.2', ...
    'Position', [65 170 115 205]);
scopeNames = {'Angle scope', 'Rate scope', 'Acceleration scope', 'Input scope'};
labels = {'theta', 'omega', 'alpha', 'u', 'v'};
sources = {'Nonlinear pendulum/1', 'Nonlinear pendulum/2', ...
    'Nonlinear pendulum/3', 'Linearizing controller/1', 'Virtual acceleration v/1'};
wire(model, {'Virtual acceleration v/1','Linearizing controller/1'; ...
    'Nonlinear pendulum/1','Linearizing controller/2'; ...
    'Nonlinear pendulum/2','Linearizing controller/3'; ...
    'Linearizing controller/1','Nonlinear pendulum/1'});
for index = 1:4
    y = 170+(index-1)*95;
    add_block('simulink/Sinks/Scope', [model '/' scopeNames{index}], ...
        'Position', [965 y 1025 y+45]);
    configuration = get_param([model '/' scopeNames{index}], 'ScopeConfiguration');
    configuration.TimeSpan = '2'; configuration.ShowGrid = true;
    configuration.ShowLegend = true;
    if index == 3
        set_param([model '/' scopeNames{index}], 'NumInputPorts', '2');
        wire(model, {'Virtual acceleration v/1','Acceleration scope/2'});
    end
    wire(model, {sources{index}, [scopeNames{index} '/1']});
end
for index = 1:numel(sources)
    parts = strsplit(sources{index}, '/');
    ports = get_param([model '/' parts{1}], 'PortHandles');
    set_param(get_param(ports.Outport(str2double(parts{2})), 'Line'), ...
        'Name', labels{index});
end
note = Simulink.Annotation(model, sprintf([ ...
    'Part I - Question 1(b): input-output feedback linearization\n' ...
    'Virtual input v is angular acceleration, not angle reference.\n' ...
    'Valid only where cos(theta) is nonzero; no stabilizing feedback yet.']));
note.Position = [60 25 1050 90];
save_system(model, fullfile(project.simulink, [model '.slx']));
Simulink.exportToVersion(model, ...
    fullfile(project.simulink, [model '_R2021a.slx']), 'R2021a');
close_system(source, 0);
end

function port(system, type, name, number, position)
add_block(['simulink/Ports & Subsystems/' type], [system '/' name], ...
    'Port', num2str(number), 'Position', position);
end

function wire(system, connections)
for index = 1:size(connections,1)
    add_line(system, connections{index,1}, connections{index,2}, 'autorouting', 'on');
end
end
