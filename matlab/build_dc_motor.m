function model = build_dc_motor
%BUILD_DC_MOTOR Part I, Question 2(a): motor with quadratic aerodynamic drag.
project = setup_project; model = 'part1_dc_motor';
load_system('simulink');
if bdIsLoaded(model), close_system(model, 0); end
new_system(model);
workspace = get_param(model, 'ModelWorkspace');
p = struct('J',0.01,'KT',0.2,'Ke',0.2,'Ra',2,'La',0.05, ...
    'd1',0.01,'d2',0.005,'theta0',0,'omega0',0,'ia0',0);
names = fieldnames(p);
for index = 1:numel(names), assignin(workspace,names{index},p.(names{index})); end
set_param(model,'SolverType','Variable-step','Solver','ode45', ...
    'RelTol','1e-8','AbsTol','1e-10','MaxStep','0.002', ...
    'StopTime','2','ReturnWorkspaceOutputs','on', ...
    'SaveOutput','off','SaveTime','off','SignalLogging','off', ...
    'Location',[40 80 1380 850]);
plant = [model '/Nonlinear DC motor'];
add_block('built-in/Subsystem',plant,'Position',[590 175 785 340]);
add_block('simulink/Ports & Subsystems/In1',[plant '/Voltage'], ...
    'Port','1','Position',[35 320 65 340]);
add_block('simulink/Signal Routing/Mux',[plant '/State and input'], ...
    'Inputs','3','Position',[120 150 125 270]);
add_block('simulink/User-Defined Functions/Fcn',[plant '/Mechanical equation'], ...
    'Expr','(KT*u(2)-d1*u(1)-d2*u(1)*abs(u(1)))/J', ...
    'Position',[200 100 485 150]);
add_block('simulink/User-Defined Functions/Fcn',[plant '/Electrical equation'], ...
    'Expr','(-Ra*u(2)-Ke*u(1)+u(3))/La', ...
    'Position',[200 290 485 340]);
add_block('simulink/Continuous/Integrator',[plant '/Angular velocity'], ...
    'InitialCondition','omega0','Position',[560 105 600 145]);
add_block('simulink/Continuous/Integrator',[plant '/Angle'], ...
    'InitialCondition','theta0','Position',[685 105 725 145]);
add_block('simulink/Continuous/Integrator',[plant '/Armature current'], ...
    'InitialCondition','ia0','Position',[560 295 600 335]);
% Passive jerk observation from the physical state derivatives, not diff().
add_block('simulink/Signal Routing/Mux',[plant '/Jerk arguments'], ...
    'Inputs','3','Position',[190 435 195 535]);
add_block('simulink/User-Defined Functions/Fcn',[plant '/Jerk equation'], ...
    'Expr','KT/J*u(3)-(d1+2*d2*abs(u(1)))/J*u(2)', ...
    'Position',[290 460 600 510]);
outNames = {'theta','omega','ia','alpha','jerk'};
outSources = {'Angle/1','Angular velocity/1','Armature current/1', ...
    'Mechanical equation/1','Jerk equation/1'};
for index = 1:5
    y = 85+90*(index-1);
    add_block('simulink/Ports & Subsystems/Out1',[plant '/' outNames{index}], ...
        'Port',num2str(index),'Position',[860 y 890 y+20]);
end
connections = {'Angular velocity/1','State and input/1'; ...
    'Armature current/1','State and input/2'; 'Voltage/1','State and input/3'; ...
    'State and input/1','Mechanical equation/1'; ...
    'State and input/1','Electrical equation/1'; ...
    'Mechanical equation/1','Angular velocity/1'; 'Angular velocity/1','Angle/1'; ...
    'Electrical equation/1','Armature current/1'; ...
    'Angular velocity/1','Jerk arguments/1'; ...
    'Mechanical equation/1','Jerk arguments/2'; ...
    'Electrical equation/1','Jerk arguments/3'; 'Jerk arguments/1','Jerk equation/1'};
for index = 1:5
    connections(end+1,:) = {outSources{index},[outNames{index} '/1']}; %#ok<AGROW>
end
wire(plant,connections);
add_block('simulink/Sources/Step',[model '/Voltage input u'], ...
    'Time','0.2','Before','0','After','1','Position',[65 180 115 220]);
wire(model,{'Voltage input u/1','Nonlinear DC motor/1'});
scopeNames = {'Angle scope','Speed scope','Current scope','Acceleration scope', ...
    'Jerk scope','Voltage scope'};
labels = [outNames {'u'}];
units = {'Angle [rad]','Speed [rad/s]','Current [A]', ...
    'Acceleration [rad/s^2]','Jerk [rad/s^3]','Voltage [V]'};
for index = 1:6
    y = 130+75*(index-1);
    add_block('simulink/Sinks/Scope',[model '/' scopeNames{index}], ...
        'Position',[1020 y 1080 y+40]);
    configuration = get_param([model '/' scopeNames{index}],'ScopeConfiguration');
    configuration.TimeSpan = '2'; configuration.ShowGrid = true;
    configuration.ShowLegend = true; configuration.YLabel = units{index};
    if index <= 5
        source = sprintf('Nonlinear DC motor/%d',index);
        ports = get_param(plant,'PortHandles'); outputPort = ports.Outport(index);
    else
        source = 'Voltage input u/1';
        ports = get_param([model '/Voltage input u'],'PortHandles'); outputPort = ports.Outport(1);
    end
    wire(model,{source,[scopeNames{index} '/1']});
    set_param(get_param(outputPort,'Line'),'Name',labels{index});
end
note = Simulink.Annotation(model,sprintf([ ...
    'Part I - Question 2(a): nonlinear DC motor plant\n' ...
    'States: theta [rad], omega [rad/s], ia [A]; initial states are zero.\n' ...
    'Voltage step: 0 to 1 V at 0.2 s. Quadratic drag opposes both speed signs.']));
note.Position = [60 20 1100 95];
save_system(model,fullfile(project.simulink,[model '.slx']));
Simulink.exportToVersion(model,fullfile(project.simulink,[model '_R2021a.slx']),'R2021a');
end

function wire(system,connections)
for index = 1:size(connections,1)
    add_line(system,connections{index,1},connections{index,2},'autorouting','on');
end
end
