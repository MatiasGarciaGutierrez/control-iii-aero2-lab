function model = build_pendulum
%BUILD_PENDULUM Part I, Question 1(a): nonlinear open-loop pendulum.
project = setup_project;
model = 'part1_pendulum';
load_system('simulink');
if bdIsLoaded(model)
    close_system(model, 0);
end
new_system(model);
workspace = get_param(model, 'ModelWorkspace');
parameters = struct('m', 0.2, 'l', 0.5, 'g', 9.81, 'k', 0.05, ...
    'theta0', 0.1, 'omega0', 0);
names = fieldnames(parameters);
for index = 1:numel(names)
    assignin(workspace, names{index}, parameters.(names{index}));
end
set_param(model, 'SolverType', 'Variable-step', 'Solver', 'ode45', ...
    'RelTol', '1e-8', 'AbsTol', '1e-10', 'MaxStep', '0.005', ...
    'StopTime', '2', 'ReturnWorkspaceOutputs', 'on', ...
    'SaveOutput', 'off', 'SaveTime', 'off', 'SignalLogging', 'off', ...
    'Location', [40 80 1380 850]);
add_block('simulink/Sources/Constant', [model '/Control input u'], ...
    'Value', '0', 'Position', [60 360 105 390]);
add_block('simulink/Math Operations/Product', [model '/Input projection'], ...
    'Position', [235 350 265 390]);
add_block('simulink/Math Operations/Gain', [model '/Inverse inertia'], ...
    'Gain', '1/(m*l^2)', 'Position', [320 350 410 390]);
add_block('simulink/Math Operations/Sum', [model '/Angular acceleration'], ...
    'Inputs', '+-+', 'Position', [505 210 535 270]);
add_block('simulink/Continuous/Integrator', [model '/Angular velocity'], ...
    'InitialCondition', 'omega0', 'Position', [620 225 655 260]);
add_block('simulink/Continuous/Integrator', [model '/Angle'], ...
    'InitialCondition', 'theta0', 'Position', [775 225 810 260]);
add_block('simulink/Math Operations/Trigonometric Function', [model '/sin theta'], ...
    'Operator', 'sin', 'Position', [200 90 245 120]);
add_block('simulink/Math Operations/Gain', [model '/Gravity'], ...
    'Gain', 'g/l', 'Position', [325 90 405 120]);
add_block('simulink/Math Operations/Gain', [model '/Friction'], ...
    'Gain', 'k/(m*l^2)', 'Orientation', 'left', ...
    'Position', [510 150 600 180]);
add_block('simulink/Math Operations/Trigonometric Function', [model '/cos theta'], ...
    'Operator', 'cos', 'Position', [110 460 155 490]);
scopeNames = {'Angle scope', 'Rate scope', 'Acceleration scope', 'Input scope'};
units = {'Angle [rad]', 'Angular velocity [rad/s]', ...
    'Angular acceleration [rad/s^2]', 'Control input u'};
positions = {[965 220 1015 260], [965 310 1015 350], ...
    [965 400 1015 440], [965 490 1015 530]};
for index = 1:numel(scopeNames)
    add_block('simulink/Sinks/Scope', [model '/' scopeNames{index}], ...
        'Position', positions{index});
    configuration = get_param([model '/' scopeNames{index}], 'ScopeConfiguration');
    configuration.ShowGrid = true;
    configuration.TimeSpan = '2';
    configuration.YLabel = units{index};
end
connections = {'Control input u/1', 'Input projection/1'; ...
    'cos theta/1', 'Input projection/2'; ...
    'Input projection/1', 'Inverse inertia/1'; ...
    'Inverse inertia/1', 'Angular acceleration/3'; ...
    'sin theta/1', 'Gravity/1'; 'Gravity/1', 'Angular acceleration/1'; ...
    'Angular velocity/1', 'Friction/1'; 'Friction/1', 'Angular acceleration/2'; ...
    'Angular acceleration/1', 'Angular velocity/1'; ...
    'Angular velocity/1', 'Angle/1'; 'Angle/1', 'sin theta/1'; ...
    'Angle/1', 'cos theta/1'; 'Angle/1', 'Angle scope/1'; ...
    'Angular velocity/1', 'Rate scope/1'; ...
    'Angular acceleration/1', 'Acceleration scope/1'; ...
    'Control input u/1', 'Input scope/1'};
for index = 1:size(connections, 1)
    add_line(model, connections{index,1}, connections{index,2}, 'autorouting', 'on');
end
sources = {'Angle', 'Angular velocity', 'Angular acceleration', 'Control input u'};
labels = {'theta', 'omega', 'alpha', 'u'};
for index = 1:numel(sources)
    ports = get_param([model '/' sources{index}], 'PortHandles');
    set_param(get_param(ports.Outport(1), 'Line'), 'Name', labels{index});
end
note = Simulink.Annotation(model, sprintf([ ...
    'Part I - Question 1(a): nonlinear pendulum, no controller\n' ...
    'theta measured from upright; theta0 = 0.1 rad, omega0 = 0 rad/s, u = 0\n' ...
    'alpha = (g/l) sin(theta) - k/(m*l^2) omega + cos(theta) u/(m*l^2)']));
note.Position = [60 10 1020 65];
save_system(model, fullfile(project.simulink, [model '.slx']));
Simulink.exportToVersion(model, ...
    fullfile(project.simulink, [model '_R2021a.slx']), 'R2021a');
end
